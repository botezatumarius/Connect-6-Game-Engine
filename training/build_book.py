"""Builds the opening book: long searches of the first positions, one per symmetry class.

The positions are black's centre stone (white to move) and every white reply with both stones
within two cells of it (black to move). Writes engine/book_moves.py.

Usage: python training/build_book.py [--seconds 30]
"""
import argparse
import sys
from itertools import combinations
from multiprocessing import Pool
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "engine"))

from board import SIZE, Board  # noqa: E402
from defines import Defines  # noqa: E402
from opening_book import SYMMETRIES, canonical  # noqa: E402
from search_engine import SearchEngine  # noqa: E402
from tools import move2msg  # noqa: E402

CENTRE = (SIZE // 2) * SIZE + SIZE // 2
NEAR = [r * SIZE + c for r in range(SIZE // 2 - 2, SIZE // 2 + 3) for c in range(SIZE // 2 - 2, SIZE // 2 + 3)
        if r * SIZE + c != CENTRE]


def opening(reply, symmetry=0):
    """Board after black's centre stone and white's `reply`, seen through a symmetry."""
    board = Board()
    board.play((SYMMETRIES[symmetry][CENTRE],), Defines.BLACK)
    if reply:
        board.play(tuple(SYMMETRIES[symmetry][cell] for cell in reply), Defines.WHITE)
    return board


def positions():
    """One representative per symmetry class: canonical key -> (white reply, its symmetry)."""
    classes = {}
    for reply in [()] + list(combinations(NEAR, 2)):
        key, symmetry = canonical(opening(reply))
        classes.setdefault(key, (reply, symmetry))
    return classes


def search(task):
    """Search the canonical orientation of a position, so the move is stored in that frame."""
    key, (reply, symmetry), seconds = task
    board = opening(reply, symmetry)
    assert canonical(board) == (key, 0)
    color = Defines.BLACK if reply else Defines.WHITE
    move, score = SearchEngine().search(board, color, Defines.MAX_DEPTH, seconds)
    return key, move2msg(move), score


def main():
    """Search every opening class in parallel and write engine/book_moves.py."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seconds", type=float, default=30, help="search time per position")
    args = parser.parse_args()

    classes = positions()
    print(f"{len(classes)} positions (from {len(NEAR) * (len(NEAR) - 1) // 2 + 1} before symmetries)")
    book = {}
    with Pool(4) as pool:  # One search per physical core, so each gets its full time.
        for key, move, score in pool.imap_unordered(search, [(k, v, args.seconds) for k, v in classes.items()]):
            book[key] = move
            print(f"{key:24s} -> {move}  ({score:.1f})", flush=True)
    lines = ['"""Opening book data, generated by training/build_book.py: canonical position -> move."""',
             "BOOK = {", *(f'    "{key}": "{book[key]}",' for key in sorted(book)), "}"]
    (ROOT / "engine" / "book_moves.py").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
